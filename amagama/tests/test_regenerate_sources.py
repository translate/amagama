"""devsupport/regenerate-sources.sh, with a stand-in amagama-manage."""

import os
import pathlib
import subprocess

import pytest

SCRIPT = pathlib.Path(__file__).resolve().parents[2] / "devsupport" / "regenerate-sources.sh"

pytestmark = pytest.mark.skipif(not SCRIPT.exists(), reason="not run from a checkout")


def test_only_searches_use_the_minutes(tmp_path):
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    manage = bin_dir / "amagama-manage"
    # Each command reports the minutes it was given, then takes 2 seconds.
    manage.write_text('#!/bin/sh\necho "$1 $AMAGAMA_SEARCH_MINUTES"\nsleep 2\n')
    manage.chmod(0o755)
    files = []
    for name, command in [("weblate-a", "weblate_sources https://w.example"),
                          ("crowdin-github", "discover_sources crowdin"),
                          ("lingui-github", "discover_sources lingui")]:
        path = tmp_path / (name + ".toml")
        path.write_text("# Generated by: amagama-manage %s\n" % command)
        files.append(str(path))
    env = dict(os.environ, PATH="%s:%s" % (bin_dir, os.environ["PATH"]),
               AMAGAMA_SEARCH_MINUTES="1")
    result = subprocess.run(["bash", str(SCRIPT), str(tmp_path / "reports")] + files,
                            capture_output=True, text=True, env=env, check=True)
    given = [line.split() for line in result.stdout.splitlines()
             if line.startswith(("weblate_sources", "discover_sources"))]
    # The Weblate command's 2 seconds aren't the searches'.
    assert [float(minutes) for _, minutes in given[:2]] == [1.0, 1.0]
    assert 0.9 <= float(given[2][1]) < 1.0


@pytest.mark.parametrize(("code", "status", "annotation", "report"), [
    (75, 0, "::warning::weblate-a: a server was unavailable", "Not regenerated"),
    (1, 1, "::error::weblate-a: amagama-manage weblate_sources", "Regenerating"),
])
def test_failed_command(tmp_path, code, status, annotation, report):
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    manage = bin_dir / "amagama-manage"
    # Writes the file, as a command does before it fails.
    manage.write_text('#!/bin/sh\necho changed >> "$(echo "$@" | sed "s/.*--output //;'
                      's/ --report.*//")"\nexit %d\n' % code)
    manage.chmod(0o755)
    repo = tmp_path / "repo"
    repo.mkdir()
    path = repo / "weblate-a.toml"
    path.write_text("# Generated by: amagama-manage weblate_sources https://w.example\n")
    git = ["git", "-C", str(repo), "-c", "user.name=t", "-c", "user.email=t@example.org"]
    subprocess.run(git[:3] + ["init", "-q"], check=True)
    subprocess.run(git + ["add", "."], check=True)
    subprocess.run(git + ["commit", "-qm", "x"], check=True)
    env = dict(os.environ, PATH="%s:%s" % (bin_dir, os.environ["PATH"]))
    # -e too: a failing command mustn't end the script.
    result = subprocess.run(["bash", "-e", str(SCRIPT), str(tmp_path / "reports"), str(path)],
                            capture_output=True, text=True, env=env, cwd=repo)
    assert result.returncode == status
    assert annotation in result.stdout
    # The file is kept as it was, and the report says why.
    assert "changed" not in path.read_text()
    assert (tmp_path / "reports" / "weblate-a.md").read_text().startswith(report)
