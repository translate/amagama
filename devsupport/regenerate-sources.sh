# Rerun the command each generated sources file names in its header, over
# that file, and write each command's --report into REPORT_DIR.
#
# Usage: regenerate-sources.sh REPORT_DIR FILE...
# Exits 1 if any command failed; the others still run. AMAGAMA_SEARCH_MINUTES,
# if set, is shared by the discover_sources commands, the ones that search:
# each searches for the minutes the ones before it left.

set -u
report_dir=$1
shift
mkdir -p "$report_dir"
status=0
search_minutes=${AMAGAMA_SEARCH_MINUTES:-0}
searched=0
for file in "$@"; do
    command=$(sed -n 's/^# Generated by: amagama-manage //p' "$file" | head -n 1)
    if awk -v minutes="$search_minutes" 'BEGIN { exit !(minutes > 0) }'; then
        # 0 doesn't stop: once none are left, a command searches for a moment.
        AMAGAMA_SEARCH_MINUTES=$(awk -v minutes="$search_minutes" -v seconds="$searched" \
            'BEGIN { left = minutes - seconds / 60; printf "%.2f", (left > 0.01 ? left : 0.01) }')
        export AMAGAMA_SEARCH_MINUTES
    fi
    started=$SECONDS
    name=$(basename "$file" .toml)
    if [ -z "$command" ]; then
        echo "::error::$file has no \"Generated by\" header"
        status=1
        continue
    fi
    echo "::group::$name: amagama-manage $command"
    # The header is the committed command: its globs are the command's, not the shell's.
    set -f
    if ! eval "amagama-manage $command --output \"$file\" --report \"$report_dir/$name.md\""; then
        echo "::error::$name: amagama-manage $command failed"
        printf 'Regenerating %s failed; see the workflow log.\n' "$name" > "$report_dir/$name.md"
        git checkout -- "$file"
        status=1
    fi
    set +f
    case $command in
        discover_sources*) searched=$((searched + SECONDS - started)) ;;
    esac
    echo "::endgroup::"
done
exit $status
